_transport_hook = None


class UpdateError(Exception):
    """Every update failure the UI should see as one clean message."""


# --------------------------------------------------------------- versioning
def parse_version(value) -> tuple:
    """'4.8.0' / 'v4.8.1-beta' -> ((4, 8, 1), is_final) comparable tuple.

    Pre-release suffixes sort BELOW the plain release (4.8.0-beta < 4.8.0),
    matching semver intent without pulling in a dependency."""
    s = str(value or "").strip().lstrip("vV").split("+", 1)[0]
    if "-" in s:
        core, pre = s.split("-", 1)
    else:
        core, pre = s, ""
    nums = []
    for part in core.split("."):
        try:
            nums.append(int(part))
        except (TypeError, ValueError):
            nums.append(0)
    while len(nums) < 3:
        nums.append(0)
    return (tuple(nums[:4]), 0 if pre else 1)


def is_newer(candidate, current) -> bool:
    try:
        return parse_version(candidate) > parse_version(current)
    except Exception:
        return False


def platform_asset_label() -> str:
    if sys.platform.startswith("win"):
        return "Windows"
    if sys.platform == "darwin":
        return "macOS"
    return "Linux"


def expected_asset_name(version: str) -> str:
    label = platform_asset_label()
    ext = "tar.gz" if label == "Linux" else "zip"
    return f"VPeeN-{version}-{label}.{ext}"


def notes_to_text(markdown: str, limit: int = 1600) -> str:
    """Release body markdown -> readable plain text for the update sheet."""
    text = markdown or ""
    text = re.sub(r"```[^\n]*```", " ", text)          # inline code spans
    text = re.sub(r"```[\s\S]*?```", " [code] ", text)  # fenced blocks
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", " ", text)  # images
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"[#>*`_]", "", text)
    lines = [ln.strip() for ln in text.splitlines()]
    out, blank = [], False
    for ln in lines:
        if not ln:
            if not blank:
                out.append("")
            blank = True
        else:
            out.append(ln)
            blank = False
    body = "\n".join(out).strip()
    if len(body) > limit:
        body = body[:limit].rsplit("\n", 1)[0] + "\n..."
    return body


# ----------------------------------------------------------------- transport
def _socks_dial(host: str, port: int, socks_port: int,
                timeout: float) -> socket.socket:
    """Connect to host:port through the local SOCKS5 (no-auth), sync version.

    The greeting and reply are parsed strictly (ATYP-aware), mirroring the
    asyncio dial used by the tunnel worker - a stray byte in the stream
    here would corrupt the HTTP session built on top of the socket."""
    s = socket.create_connection(("127.0.0.1", socks_port), timeout)
    try:
        s.settimeout(timeout)
        s.sendall(b"\x05\x01\x00")
        greet = _recv_exact(s, 2)
        if greet != b"\x05\x00":
            raise OSError(f"SOCKS5 rejected no-auth ({greet!r})")
        hostb = host.encode("idna") if not _is_ip_literal(host) else \
            host.encode("ascii")
        if b":" in hostb:      # IPv6 literal -> ATYP 4
            import ipaddress
            raw = ipaddress.IPv6Address(host).packed
            req = b"\x05\x01\x00\x04" + raw
        elif not _is_ip_literal(host):
            if len(hostb) > 255:
                raise OSError("hostname too long for SOCKS5")
            req = b"\x05\x01\x00\x03" + bytes([len(hostb)]) + hostb
        else:
            import ipaddress
            raw = ipaddress.IPv4Address(host).packed
            req = b"\x05\x01\x00\x01" + raw
        req += (port).to_bytes(2, "big")
        s.sendall(req)
        rep = _recv_exact(s, 4)
        if rep[1] != 0:
            raise OSError(f"SOCKS5 CONNECT failed (code {rep[1]})")
        atyp = rep[3]
        if atyp == 0x01:
            _recv_exact(s, 6)
        elif atyp == 0x04:
            _recv_exact(s, 18)
        elif atyp == 0x03:
            n = _recv_exact(s, 1)[0]
            _recv_exact(s, n + 2)
        else:
            raise OSError(f"unexpected SOCKS5 ATYP {atyp}")
        return s
    except Exception:
        try:
            s.close()
        except OSError:
            pass
        raise


def _recv_exact(s: socket.socket, n: int) -> bytes:
    buf = b""
    while len(buf) < n:
        chunk = s.recv(n - len(buf))
        if not chunk:
            raise OSError("connection closed mid-reply")
        buf += chunk
    return buf


def _is_ip_literal(host: str) -> bool:
    import ipaddress
    try:
        ipaddress.ip_address(str(host).strip("[]"))
        return True
    except ValueError:
        return False


class _HttpResponse:
    """Minimal response wrapper: .status, .read(n), .getheader(name),
    .close().  Produced by _open_url (or the test transport hook)."""

    def __init__(self, status, body: bytes, headers=None):
        self.status = status
        self._body = body
        self._pos = 0
        self._headers = {str(k).lower(): v for k, v in (headers or {}).items()}

    def getheader(self, name, default=None):
        return self._headers.get(str(name).lower(), default)

    def read(self, n=-1):
        if n is None or n < 0:
            out = self._body[self._pos:]
            self._pos = len(self._body)
        else:
            out = self._body[self._pos:self._pos + n]
            self._pos += len(out)
        return out

    def close(self):
        pass

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()
        return False


def _open_url(url: str, socks_port=None, timeout=CONNECT_TIMEOUT):
    """GET `url`, following redirects; returns a response object.

    Per hop the DIRECT transport is tried first and the local SOCKS5
    second (when a socks_port is given) - GitHub is throttled or blocked
    outright on some networks, and the app's own proxy is then the only
    road out.  Redirects from GitHub's CDN are followed manually because
    http.client does not chase Location for us."""
    if _transport_hook is not None:
        return _transport_hook(url, timeout)

    scheme, host, port, path = _split_url(url)
    transports = [None] + ([socks_port] if socks_port else [])
    last_exc = None
    for _hop in range(MAX_REDIRECTS + 1):
        redirected = None
        for via in transports:
            conn = None
            try:
                sock, ssl_on = _connect_transport(host, port, scheme, via,
                                                  timeout)
                conn = _http_conn(host, port, ssl_on, sock, timeout)
                conn.request("GET", path, headers={
                    "Host": host,
                    "User-Agent": _USER_AGENT,
                    "Accept": "*/*",
                    "Accept-Encoding": "identity",
                    "Connection": "close",
                })
                resp = conn.getresponse()
                resp._vpeen_conn = conn          # keep the socket referenced
                if resp.status in (301, 302, 303, 307, 308):
                    loc = resp.getheader("Location")
                    try:
                        resp.read()             # drain before redirect
                        resp.close()
                    except Exception:
                        pass
                    redirected = loc or ""
                    break                        # retry both transports
                if resp.status != 200:
                    try:
                        resp.read()
                        resp.close()
                    except Exception:
                        pass
                    raise UpdateError(f"HTTP {resp.status} from {host}")
                return resp
            except UpdateError:
                raise
            except Exception as e:
                last_exc = e
                try:
                    if conn is not None:
                        conn.close()
                except Exception:
                    pass
        if redirected is None:
            # every transport failed on this hop
            raise UpdateError(f"could not reach {host} "
                              f"({last_exc or 'no transports'})")
        if not redirected:
            raise UpdateError("redirect without a Location header")
        if redirected.startswith("/"):
            path = redirected
        else:
            scheme, host, port, path = _split_url(redirected)
    raise UpdateError("too many redirects while downloading")


def _split_url(url: str):
    from urllib.parse import urlsplit
    u = urlsplit(url)
    scheme = u.scheme or "https"
    host = u.hostname or ""
    port = u.port or (443 if scheme == "https" else 80)
    path = u.path or "/"
    if u.query:
        path += "?" + u.query
    return scheme, host, int(port), path


def _connect_transport(host, port, scheme, via, timeout):
    """Plain or SOCKS-routed TCP (+TLS) socket to host:port."""
    if via:
        sock = _socks_dial(host, port, int(via), timeout)
    else:
        sock = socket.create_connection((host, port), timeout)
    if scheme == "https":
        ctx = ssl.create_default_context()
        sock = ctx.wrap_socket(sock, server_hostname=host)
        return sock, True
    return sock, False


def _http_conn(host, port, ssl_on, sock, timeout):
    conn = (http.client.HTTPSConnection(host, port, timeout=timeout)
            if ssl_on else http.client.HTTPConnection(host, port,
                                                      timeout=timeout))
    conn.sock = sock                     # pre-connected: connect() is skipped
    return conn


def _fetch_json(url, socks_port=None, timeout=CONNECT_TIMEOUT) -> dict:
    with _open_url(url, socks_port=socks_port, timeout=timeout) as resp:
        body = resp.read()
    try:
        data = json.loads(body.decode("utf-8", "replace"))
    except ValueError:
        raise UpdateError("GitHub API returned malformed JSON")
    if not isinstance(data, dict):
        raise UpdateError("GitHub API returned an unexpected shape")
    return data


# -------------------------------------------------------------------- checks
def build_update_info(current_version: str, release: dict,
                      sums: "dict[str, str] | None",
                      socks_port=None, strict: bool = True) -> dict:
    """Release JSON -> UI-facing update info dict (no I/O).

    strict=True (default): an available release whose asset cannot be
    verified against SHA256SUMS.txt raises UpdateError - callers that
    merely CHECK the version use strict=False to surface the situation
    as info['checksum_error'] instead (the user still learns a newer
    version exists; the INSTALL refuses to run without a hash)."""
    tag = str(release.get("tag_name") or "").strip()
    version = tag.lstrip("vV") or "?"
    if not is_newer(version, current_version):
        return {"status": "latest", "latest": version}
    label = platform_asset_label()
    expected = expected_asset_name(version)
    assets = {a.get("name", ""): a for a in release.get("assets", [])
              if isinstance(a, dict)}
    asset = assets.get(expected)
    if asset is None:
        # tolerate naming drift (e.g. a future '-windows-amd64' label)
        cands = [a for n, a in assets.items()
                 if label.lower() in n.lower()
                 and version in n and n.endswith((".zip", ".tar.gz"))]
        if not cands:
            raise UpdateError(
                f"release v{version} has no asset for {label}")
        asset = cands[0]
    name = asset.get("name", expected)
    if sums is None or name not in sums:
        msg = (f"release v{version} lacks a SHA256SUMS.txt entry for "
               f"'{name}' - refusing an unverifiable download")
        if strict:
            raise UpdateError(msg)
        # tolerant path (check only): report it, the installer will refuse
        return {
            "status": "available",
            "version": version,
            "tag": tag,
            "asset": name,
            "url": asset.get("browser_download_url") or "",
            "size": int(asset.get("size") or 0),
            "sha256": "",
            "published_at": str(release.get("published_at") or ""),
            "notes": notes_to_text(release.get("body") or ""),
            "checksum_error": msg,
        }
    return {
        "status": "available",
        "version": version,
        "tag": tag,
        "asset": name,
        "url": asset.get("browser_download_url") or "",
        "size": int(asset.get("size") or 0),
        "sha256": sums[name],
        "published_at": str(release.get("published_at") or ""),
        "notes": notes_to_text(release.get("body") or ""),
    }


def fetch_sums(release: dict, socks_port=None) -> "dict[str, str]":
    """{asset name: sha256} from the release's SHA256SUMS.txt asset."""
    assets = {a.get("name", ""): a for a in release.get("assets", [])
              if isinstance(a, dict)}
    asset = assets.get(SUMS_NAME)
    if asset is None:
        raise UpdateError("this release carries no SHA256SUMS.txt - "
                          "self-update needs a checksummed release")
    url = asset.get("browser_download_url") or ""
    if not url:
        raise UpdateError("SHA256SUMS.txt has no download URL")
    with _open_url(url, socks_port=socks_port) as resp:
        text = resp.read().decode("utf-8", "replace")
    sums = {}
    for line in text.splitlines():
        parts = line.split()
        if len(parts) >= 2 and re.fullmatch(r"[0-9a-fA-F]{64}", parts[0]):
            sums[parts[-1]] = parts[0].lower()
    return sums


def check_for_update(current_version: str, socks_port=None) -> dict:
    """Full check: API -> release JSON -> sums -> info dict.

    Retries the API once through SOCKS when a socks_port is provided and
    the direct call failed (GitHub is throttled on some networks)."""
    release = None
    last = None
    for via in ([None] + ([socks_port] if socks_port else [])):
        try:
            release = _fetch_json(API_LATEST, socks_port=via)
            break
        except Exception as e:
            last = e
    if release is None:
        raise UpdateError(f"update check failed ({last})")
    try:
        sums = fetch_sums(release, socks_port=socks_port)
    except UpdateError as e:
        # still report the version, but mark installs as impossible
        info = build_update_info(current_version, release, None, socks_port,
                                  strict=False)
        if info.get("status") == "available":
            info["checksum_error"] = str(e)
        return info
    return build_update_info(current_version, release, sums, socks_port)


# ---------------------------------------------------------------- downloads
def download_to(url: str, dest: str, expected_sha256: str,
                socks_port=None, progress=None, expected_size: int = 0):
    """Stream `url` into `dest` (atomic), verifying the SHA256.

    progress(done_bytes, total_bytes) is called from the worker thread.
    Transport order: direct first, then the SOCKS proxy twice (a proxy path,
    once established, is usually the reliable one on blocked networks).
    A mismatched hash deletes the staged file and raises - the user NEVER
    ends up running an unverified build."""
    ensure_private_dir(os.path.dirname(dest))
    attempts = [None] + ([socks_port] * 2 if socks_port else [None])
    last = None
    for via in attempts:
        tmp = dest + ".part"
        try:
            with _open_url(url, socks_port=via) as resp:
                total = expected_size or int(
                    resp.getheader("Content-Length") or 0)
                done = 0
                hasher = hashlib.sha256()
                with open(tmp, "wb") as out:
                    while True:
                        chunk = resp.read(65536)
                        if not chunk:
                            break
                        out.write(chunk)
                        hasher.update(chunk)
                        done += len(chunk)
                        if progress:
                            try:
                                progress(done, total)
                            except Exception:
                                pass
            digest = hasher.hexdigest()
            if expected_sha256 and digest.lower() != \
                    expected_sha256.lower():
                raise UpdateError(
                    f"checksum mismatch for {os.path.basename(dest)} "
                    f"(got {digest[:16]}..., want "
                    f"{expected_sha256[:16]}...) - download discarded")
            if os.path.exists(dest):
                os.unlink(dest)
            os.replace(tmp, dest)
            return done
        except Exception:
            try:
                if os.path.exists(tmp):
                    os.unlink(tmp)
            except OSError:
                pass
            last = sys.exc_info()[1]
    raise UpdateError(f"download failed after all attempts ({last})")


# ------------------------------------------------------------------- staging
def _archive_kind(archive_path: str) -> str:
    """Actual archive format by MAGIC BYTES, extension as a hint only.

    v4.8.0: the updater must never trust the asset's file name - a
    repackaged asset (zip bytes under a .tar.gz name or vice versa)
    would otherwise die inside tarfile/zipfile with an opaque error.
    The SHA256 check has already proven these are EXACTLY the bytes CI
    shipped; this only decides how to unpack them."""
    try:
        with open(archive_path, "rb") as f:
            head = f.read(6)
    except OSError:
        head = b""
    if head[:4] in (b"PK\x03\x04", b"PK\x05\x06", b"PK\x07\x08"):
        return "zip"
    if head[:2] == b"\x1f\x8b":
        return "tar"
    # extension fallback (uncompressed tar / unknown magic)
    return "zip" if archive_path.endswith(".zip") else "tar"


def _safe_member(name: str, base: str) -> "str | None":
    """Normalized safe path inside base, or None for anything suspicious."""
    name = name.replace("\\", "/").lstrip("/")
    if not name or ".." in name.split("/") or name.startswith("/"):
        return None
    joined = os.path.normpath(os.path.join(base, name))
    base_abs = os.path.abspath(base)
    if not (os.path.abspath(joined) == base_abs or
            os.path.abspath(joined).startswith(base_abs + os.sep)):
        return None
    return joined


def stage_archive(archive_path: str, version: str) -> dict:
    """Extract the downloaded archive into UPDATE_DIR/<version>/.

    Returns {"kind": "exe"|"app", "path": <staged target>, "dir": staging}.
    - Windows zip  -> .../VPeeN.exe        (onefile executable)
    - Linux tar.gz -> .../VPeeN            (onefile executable)
    - macOS zip    -> .../VPeeN.app        (bundle directory)
    """
    stage_dir = os.path.join(UPDATE_DIR, f"v{version}-{platform_asset_label()}")
    if os.path.isdir(stage_dir):
        shutil.rmtree(stage_dir, ignore_errors=True)
    os.makedirs(stage_dir, exist_ok=True)
    ensure_private_dir(stage_dir)
    if _archive_kind(archive_path) == "zip":
        with zipfile.ZipFile(archive_path) as zf:
            for info in zf.infolist():
                target = _safe_member(info.filename, stage_dir)
                if target is None:
                    continue
                if info.filename.endswith("/"):
                    os.makedirs(target, exist_ok=True)
                    continue
                os.makedirs(os.path.dirname(target), exist_ok=True)
                with zf.open(info) as src, open(target, "wb") as out:
                    shutil.copyfileobj(src, out, 1 << 20)
                if info.external_attr and (info.external_attr >> 16) & 0o111:
                    os.chmod(target, 0o755)
        # locate the staged target
        app = os.path.join(stage_dir, "VPeeN.app")
        exe = os.path.join(stage_dir, "VPeeN.exe")
        lin = os.path.join(stage_dir, "VPeeN")
        if os.path.isdir(app):
            return {"kind": "app", "path": app, "dir": stage_dir}
        if os.path.isfile(exe):
            return {"kind": "exe", "path": exe, "dir": stage_dir}
        if os.path.isfile(lin):
            os.chmod(lin, 0o755)
            return {"kind": "exe", "path": lin, "dir": stage_dir}
        raise UpdateError("archive did not contain VPeeN(.exe|.app)")
    # tar.gz / tgz / uncompressed tar (decided by _archive_kind above)
    with tarfile.open(archive_path, "r:gz") as tf:
        for member in tf.getmembers():
            target = _safe_member(member.name, stage_dir)
            if target is None:
                continue
            if member.isdir():
                os.makedirs(target, exist_ok=True)
                continue
            if not member.isfile():
                continue         # no devices, no symlinks, ever
            os.makedirs(os.path.dirname(target), exist_ok=True)
            with tf.extractfile(member) as src, \
                    open(target, "wb") as out:
                shutil.copyfileobj(src, out, 1 << 20)
            os.chmod(target, 0o755)
    exe = os.path.join(stage_dir, "VPeeN")
    if os.path.isfile(exe):
        return {"kind": "exe", "path": exe, "dir": stage_dir}
    raise UpdateError("archive did not contain the VPeeN executable")


# ------------------------------------------------------------------ install
def _is_windows() -> bool:
    """Injected/overridden by tests (sys.platform itself is not patchable
    safely on a running interpreter)."""
    return sys.platform.startswith("win")


def _winreg_write_str(path: str, name: str, value: str) -> None:
    """Windows-only: write one HKCU string value.  Overridden by tests."""
    import winreg
    with winreg.OpenKey(winreg.HKEY_CURRENT_USER, path, 0,
                        winreg.KEY_SET_VALUE) as k:
        winreg.SetValueEx(k, name, 0, winreg.REG_SZ, str(value))


def _installed_via_setup() -> bool:
    r"""True when THIS running exe lives inside an Inno Setup install.

    The installer writes HKCU\...\Uninstall\VPeeN_is1\InstallLocation; a
    portable (zip) deployment never creates that key, so the updater can
    tell the two apart and only syncs the registry for installed builds.
    Overridden by tests."""
    if not _is_windows():
        return False
    try:
        import winreg
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, UNINSTALL_KEY, 0,
                            winreg.KEY_READ) as k:
            loc, _typ = winreg.QueryValueEx(k, "InstallLocation")
        if not loc:
            return False
        exe = os.path.normcase(os.path.abspath(sys.executable))
        base = os.path.normcase(os.path.abspath(loc))
        return exe.startswith(base + os.sep) or os.path.dirname(exe) == base
    except Exception:
        return False


def refresh_installed_version(version: str) -> bool:
    """v4.9.0: after a self-update swap on an INSTALLED build, sync the
    'Apps & Features' DisplayVersion (it otherwise stays at whatever the
    setup exe last wrote).  Purely cosmetic - any failure is swallowed
    because the swap itself already succeeded."""
    if not _is_windows():
        return False
    try:
        if not _installed_via_setup():
            return False
        _winreg_write_str(UNINSTALL_KEY, "DisplayVersion", str(version))
        return True
    except Exception:
        return False


def _running_target() -> "tuple[str, str] | None":
    """(kind, target path) of THIS running installation, or None when the
    app is not a frozen build (source installs never self-swap)."""
    if not getattr(sys, "frozen", False):
        return None
    exe = os.path.abspath(sys.executable)
    # macOS: .../VPeeN.app/Contents/MacOS/VPeeN  -> bundle dir two levels up
    if sys.platform == "darwin" and re.search(
            re.escape(os.sep + "Contents" + os.sep + "MacOS" + os.sep), exe):
        app_dir = os.path.dirname(os.path.dirname(os.path.dirname(exe)))
        if os.path.isdir(app_dir) and app_dir.endswith(".app"):
            return ("app", app_dir)
    return ("exe", exe)


def install_staged(staged: dict, expect_version: str) -> None:
    """Swap the staged build into the running install location.

    Rollback: if moving the new build into place fails, the old file is
    restored, so a half-finished update can never leave the app missing.
    The displaced old build is kept as `<target>.old` / `<target>.old-<ts>`
    and removed by sweep_leftovers() on the next boot."""
    target = _running_target()
    if target is None:
        raise UpdateError("this is a source installation - use git to update")
    kind, tpath = target
    if staged.get("kind") != kind:
        raise UpdateError(f"staged build is a {staged.get('kind')} but this "
                          f"installation is a {kind}")
    src = staged["path"]
    if not os.path.exists(src):
        raise UpdateError("staged build vanished - restart the update")
    if kind == "exe":
        old = tpath + ".old"
        try:
            if os.path.exists(old):
                os.unlink(old)          # previous sweep leftovers
        except OSError:
            pass
        os.replace(tpath, old)
        try:
            shutil.copyfile(src, tpath)
            if os.name == "posix":
                os.chmod(tpath, 0o755)
        except Exception:
            try:
                os.replace(old, tpath)  # rollback - never ship a hole
            except OSError:
                pass
            raise UpdateError("could not place the new executable "
                              "(original restored)")
        # v4.9.0: installed (setup-exe) builds keep their uninstall entry
        # in sync after the in-place swap; failures are cosmetic, not fatal.
        refresh_installed_version(expect_version)
    else:      # app bundle directory
        old = f"{tpath}.old-{int(time.time())}"
        os.rename(tpath, old)
        try:
            shutil.move(src, tpath)
        except Exception:
            try:
                os.rename(old, tpath)
            except OSError:
                pass
            raise UpdateError("could not place the new app bundle "
                              "(original restored)")
    _write_pending(expect_version)


def _write_pending(version: str) -> None:
    try:
        ensure_private_dir(UPDATE_DIR)
        with open(PENDING_MARKER, "w", encoding="utf-8") as f:
            json.dump({"expect": version, "at": time.time()}, f)
    except OSError:
        pass


def check_pending(current_version: str) -> "str | None":
    """Boot-time verification of a completed swap.

    Returns the expected version when a pending marker exists (deleted in
    the process); compare with the RUNNING version to prove the swap."""
    try:
        with open(PENDING_MARKER, "r", encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError):
        return None
    try:
        os.remove(PENDING_MARKER)
    except OSError:
        pass
    return data.get("expect") if isinstance(data, dict) else None


def sweep_leftovers() -> None:
    """Remove update leftovers from previous runs (best effort, silent).

    - <exe>.old / *.old-<ts> siblings of the running binary / bundle
      (the old image is undeletable while it IS the running image, so it
      is always exactly one boot behind)
    - staging directories older than a week
    """
    try:
        target = _running_target()
        if target is not None:
            kind, tpath = target
            parent = os.path.dirname(tpath)
            base = os.path.basename(tpath)
            for name in os.listdir(parent):
                if name == base:
                    continue
                if name == base + ".old" or \
                        name.startswith(base + ".old-"):
                    path = os.path.join(parent, name)
                    if os.path.isdir(path):
                        shutil.rmtree(path, ignore_errors=True)
                    else:
                        try:
                            os.unlink(path)
                        except OSError:
                            pass
        if os.path.isdir(UPDATE_DIR):
            now = time.time()
            for name in os.listdir(UPDATE_DIR):
                path = os.path.join(UPDATE_DIR, name)
                try:
                    if os.path.isdir(path) and \
                            now - os.path.getmtime(path) > STAGING_MAX_AGE:
                        shutil.rmtree(path, ignore_errors=True)
                except OSError:
                    pass
    except Exception:
        pass


def restart(executable: str = None, argv: "list[str] | None" = None) -> None:
    """Replace THIS process with the (new) executable.  Never returns."""
    exe = executable or sys.executable
    os.execv(exe, argv or [exe])
