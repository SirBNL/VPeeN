"""
VPeeN self-update (v4.8.0 "Sentinel").

Automatic update detection + one-click install:

    1. CHECK   - GitHub /releases/latest (unauthenticated JSON API).
    2. VERIFY  - the release's SHA256SUMS.txt (generated by CI in the same
                 job that uploads the assets) pins every asset hash; the
                 download is refused when the checksum file is missing.
    3. DOWNLOAD- streamed to ~/.vpeen/update/ with progress; retried
                 THROUGH the local SOCKS5 proxy when GitHub is unreachable
                 directly (it often is, on the very networks that need a
                 VPN most).
    4. INSTALL - staged swap of the running executable / .app bundle:
                 the old file is renamed aside (never deleted while it is
                 the running image), the verified new one moved into place,
                 and a pending-update marker is written so the NEXT start
                 can prove the swap actually landed.
    5. RESTART - os.execv into the new binary after a clean disconnect.

Every mutating step has a rollback; leftovers (*.old / staging dirs) are
swept on the next boot by sweep_leftovers().

Standard library only, like the rest of the core.
"""
